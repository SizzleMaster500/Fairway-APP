import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const html = fs.readFileSync(path.join(root,'index.html'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.webmanifest'),'utf8'));
for(const f of ['styles.css','js/storage.js','js/handicap.js','js/player.js','js/app.js','icon-192.png','icon-512.png','apple-touch-icon.png']) assert(fs.existsSync(path.join(root,f)),`Missing ${f}`);
for(const f of ['storage','handicap','player','app']) assert(html.includes(`./js/${f}.js`),`Missing script ${f}`);
assert.equal(manifest.start_url,'./');
assert(html.includes('v0.9.8'));
for(const f of ['storage','handicap','player','app']) new vm.Script(fs.readFileSync(path.join(root,`js/${f}.js`),'utf8'));
const ctx=vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root,'js/app.js'),'utf8').split('function validStrokeIndices(')[1].split('\n')[0].replace(/^/,'function validStrokeIndices('),ctx);
assert.equal(vm.runInContext('validStrokeIndices([1,3,5,7,9,11,13,15,17],9)',ctx),true);
assert.equal(vm.runInContext('validStrokeIndices([1,3,5,7,9,11,13,15,19],9)',ctx),false);
assert.equal(vm.runInContext('validStrokeIndices([1,3,5,7,9,11,13,15,15],9)',ctx),false);
assert.equal(vm.runInContext('validStrokeIndices(Array(9).fill(null),9)',ctx),true);
assert.equal(vm.runInContext('validStrokeIndices(Array.from({length:18},(_,i)=>i+1),18)',ctx),true);
console.log('PASS: required files, script parsing, manifest, version and 9/18-hole Stroke Index validation');
